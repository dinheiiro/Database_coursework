			--СОЗДАНИЕ ТАБЛИЦ
CREATE TABLE Departments 
		(DepartmentID INT PRIMARY KEY IDENTITY(1,1),
		 DepartmentName NVARCHAR(255) NOT NULL);

CREATE TABLE Employees
		(EmployeeID INT PRIMARY KEY IDENTITY(1,1),
		 FirstName NVARCHAR(255) NOT NULL,
		 LastName NVARCHAR(255) NOT NULL,
		 MiddleName NVARCHAR(255),
		 BirthDate DATE NOT NULL,
		 HireDate DATE NOT NULL,
		 Position NVARCHAR(255),
		 DepartmentID INT FOREIGN KEY REFERENCES Departments(DepartmentID));

CREATE TABLE Vacations
		(VacationID INT PRIMARY KEY IDENTITY(1,1),
		 StartDate DATE NOT NULL,
		 EndDate DATE NOT NULL,
		 EmployeeID INT FOREIGN KEY REFERENCES Employees(EmployeeID));

CREATE TABLE Suppliers
		(SupplierID INT PRIMARY KEY IDENTITY(1,1),
		 SupplierName NVARCHAR(255) NOT NULL,
		 ContactPhone NVARCHAR(25));

CREATE TABLE Products 
		(ProductID INT PRIMARY KEY IDENTITY(1,1),
		 ProductName NVARCHAR(255) NOT NULL,
		 Unit NVARCHAR(50), --штук, кг, л и т.д.
		 ShelfLifeDays INT, --срок годности в днях
		 MinStockLevel INT, --минимальный остаток для заказа
		 DepartmentID INT FOREIGN KEY REFERENCES Departments(DepartmentID));

CREATE TABLE Stock
		(StockID INT PRIMARY KEY IDENTITY(1,1),
		 Quantity INT NOT NULL,
		 ExpiryDate DATE,
		 ProductID INT FOREIGN KEY REFERENCES Products(ProductID));

CREATE TABLE Sales
		(SaleID INT PRIMARY KEY IDENTITY(1,1),
		 SaleDateTime DATETIME NOT NULL,
		 CashRegister NVARCHAR(10) NOT NULL, 
		 EmployeeID INT NULL FOREIGN KEY REFERENCES Employees(EmployeeID))

CREATE TABLE SaleItems
		(SalesItemsID INT PRIMARY KEY IDENTITY(1,1),
		 Quantity INT NOT NULL,
		 UnitPrice DECIMAL(10,2) NOT NULL,
		 SaleID INT FOREIGN KEY REFERENCES Sales(SaleID),
		 ProductID INT FOREIGN KEY REFERENCES Products(ProductID));

CREATE TABLE PurchaseOrders
		(OrderID INT PRIMARY KEY IDENTITY(1,1),
		 OrderDate DATE NOT NULL,
		 OrderStatus NVARCHAR(50), --одижается, доставлен, отменен
		 SupplierID INT FOREIGN KEY REFERENCES Suppliers(SupplierID));

CREATE TABLE OrderItems
		(OrderItem INT PRIMARY KEY IDENTITY(1,1),
		 Quantity INT NOT NULL,
		 StockID INT FOREIGN KEY REFERENCES Stock(StockID),
		 OrderID INT FOREIGN KEY REFERENCES PurchaseOrders(OrderID));

